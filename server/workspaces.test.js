import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
const directory=await mkdtemp(path.join(os.tmpdir(),'pocketlab-workspaces-'));
process.env.POCKETLAB_DATA_DIR=directory;
for(const key of ['NEO4J_URI','NEO4J_USERNAME','NEO4J_PASSWORD'])delete process.env[key];
const {initializeWorkspaces,workspaces,createWorkspace,createExperiment,listWorkspaces,BATTERY_ID}=await import('./workspaces.js');
after(async()=>{await rm(directory,{recursive:true,force:true});});
test('workspaces persist, isolate research and experiments, and migrate the battery notebook',async()=>{
  const legacyJob={id:'legacy-research',idea:'Battery arbitrage',papers:[{id:'paper-1'}]};
  const jobs=new Map([[legacyJob.id,legacyJob]]);let saved=0;
  await initializeWorkspaces(jobs,async()=>saved++);
  assert.equal(legacyJob.workspaceId,BATTERY_ID);assert.equal(saved,1);
  assert.equal(workspaces.get(BATTERY_ID).name,'Battery arbitrage');
  const independent=await createWorkspace({name:'New research idea',idea:'Can a separate experiment improve retrieval?',domain:'Artificial intelligence'});
  assert.notEqual(independent.id,BATTERY_ID);assert.equal(independent.experiments.length,0);
  const experiment=await createExperiment(independent,{name:'Compare retrieval approaches',hypothesis:'Combining retrieval strategies will improve evidence coverage.'});
  assert.equal(experiment.status,'planned');assert.equal(independent.experiments.length,1);
  assert.equal(workspaces.get(BATTERY_ID).experiments.length,0);
  const listed=await listWorkspaces(jobs);
  assert.equal(listed.find(w=>w.id===BATTERY_ID).stats.researchRuns,1);
  assert.equal(listed.find(w=>w.id===independent.id).stats.researchRuns,0);
  assert.equal(listed.find(w=>w.id===independent.id).stats.sources,0);
  workspaces.clear();await initializeWorkspaces(jobs,async()=>saved++);
  assert.equal(workspaces.size,2);assert.equal(workspaces.get(independent.id).experiments[0].id,experiment.id);
  assert.equal(saved,1,'Previously scoped research is not migrated a second time');
});
